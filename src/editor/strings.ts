export const STRINGS = { en, de };
export type Lang = keyof typeof STRINGS;

/** The language to start in: what the person chose before, else German for a German browser. */
export function pickLang(stored: string | null, browser: string | undefined): Lang {
  if (stored === "en" || stored === "de") return stored;
  return (browser ?? "").toLowerCase().startsWith("de") ? "de" : "en";
}
